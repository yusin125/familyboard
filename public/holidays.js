// 대한민국 공휴일 로컬 데이터 (외부 API 미사용)
// 고정 날짜 공휴일은 정확하며, 음력 기반 공휴일(설날/부처님오신날/추석)은
// 표시된 연도까지는 통상적으로 알려진 날짜를 기준으로 등록했습니다.
// 매년 갱신이 필요할 수 있는 부분이니, 새 연도가 추가되면 이 파일만 수정하면 됩니다.
(function () {
  function fixedHolidaysForYear(year) {
    return {
      [`${year}-01-01`]: '신정',
      [`${year}-03-01`]: '삼일절',
      [`${year}-05-05`]: '어린이날',
      [`${year}-06-06`]: '현충일',
      [`${year}-08-15`]: '광복절',
      [`${year}-10-03`]: '개천절',
      [`${year}-10-09`]: '한글날',
      [`${year}-12-25`]: '크리스마스'
    };
  }

  // 음력 기반 공휴일 (best-effort, 매년 갱신 필요)
  const LUNAR_HOLIDAYS = {
    2025: {
      '2025-01-28': '설날 연휴',
      '2025-01-29': '설날',
      '2025-01-30': '설날 연휴',
      '2025-05-05': '부처님오신날',
      '2025-10-05': '추석 연휴',
      '2025-10-06': '추석',
      '2025-10-07': '추석 연휴'
    },
    2026: {
      '2026-02-16': '설날 연휴',
      '2026-02-17': '설날',
      '2026-02-18': '설날 연휴',
      '2026-05-24': '부처님오신날',
      '2026-09-24': '추석 연휴',
      '2026-09-25': '추석',
      '2026-09-26': '추석 연휴'
    },
    2027: {
      '2027-02-06': '설날 연휴',
      '2027-02-07': '설날',
      '2027-02-08': '설날 연휴',
      '2027-05-13': '부처님오신날',
      '2027-09-14': '추석 연휴',
      '2027-09-15': '추석',
      '2027-09-16': '추석 연휴'
    },
    2028: {
      '2028-01-26': '설날 연휴',
      '2028-01-27': '설날',
      '2028-01-28': '설날 연휴',
      '2028-05-02': '부처님오신날',
      '2028-10-02': '추석 연휴',
      '2028-10-03': '추석',
      '2028-10-04': '추석 연휴'
    }
  };

  const holidays = {};
  for (let y = 2024; y <= 2032; y++) {
    Object.assign(holidays, fixedHolidaysForYear(y));
  }
  Object.values(LUNAR_HOLIDAYS).forEach((yearMap) => Object.assign(holidays, yearMap));

  window.FB_HOLIDAYS = holidays;
})();
